function matDiff(matOld, matNew, opt = {}) {

    //check, matOld與matNew為必須參數(陣列且各列為陣列, []合法), 無效throw(訊息不帶值), 檢測序為matOld陣列、matNew陣列、matOld各列、matNew各列
    //各列於此檢測而非交由arrDiff, 使訊息用本函數之參數名(arrDiff之訊息為arrOld/arrNew)
    if (!isarr(matOld)) {
        throw new Error('invalid matOld: must be an array')
    }
    if (!isarr(matNew)) {
        throw new Error('invalid matNew: must be an array')
    }
    //snap, 各列之快照(依索引走訪, 空洞視為undefined而無效; 訊息指出列號, 只含索引不含值; 檢查之列即交arrDiff之列)
    let snap = (mat, name) => {
        let rows = []
        for (let i = 0; i < mat.length; i++) {
            let r = mat[i]
            if (!isarr(r)) {
                throw new Error(`invalid ${name}: row[${i}] is not an array`)
            }
            rows.push(r)
        }
        return rows
    }
    let rowsOld = snap(matOld, 'matOld')
    let rowsNew = snap(matNew, 'matNew')
    if (size(rowsOld) === 0 && size(rowsNew) === 0) {
        return {
            diff: [],
            dfs: [],
        }
    }

    //arrDiff, 固定矩陣模式(逐列再逐格比對), 不轉傳其他opt(opt.dls、opt.dlq已移除)
    let r = arrDiff(rowsOld, rowsNew, { mode: 'matrix' })

    return r
}


export default matDiff
