//主機位址(單一項)可回顯之樣式: [主機名稱或[IPv6]][:最多5位數字之port]
const RE_HOSTPORT = /^(?:[A-Za-z0-9._-]+|\[[0-9A-Fa-f:.]+\])(?::[0-9]{1,5})?$/


//isSafeHosts, 主機位址項(以,分隔)是否皆可回顯
let isSafeHosts = (x) => {
    return x === '' || x.split(',').every((h) => RE_HOSTPORT.test(h))
}


